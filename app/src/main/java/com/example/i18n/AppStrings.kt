/**
 * PhonAcq 集中文案与国际化资源包 (Single Source of Truth for all non-doc UI & business copy).
 *
 * 设计约束：
 * 1. 纯 Kotlin + Compose Runtime `@Immutable`，严禁引入任何 `android.*` 依赖，以同时兼容 Android 与 Windows Desktop (JVM) 编译。
 * 2. 本文件收录除百科（Encyclopedia）、使用手册（UserManual）及贴士动画脚本（TipIllustration*）外的所有界面文案、
 *    提示文本、导出报告说明、语音质量引导语及较长的声学/语音学术语解释，便于集中审阅与后续多语言（i18n）翻译。
 * 3. 数据库、SharedPreferences、无线协议及评测器内部仍保留稳定的规范键值（如 `"正常"`、`"男"`、`"女"`、`"中"`），
 *    UI 展示统一通过本文件中对应的 `S` 属性与辅助映射函数呈现。
 */
object AppStrings {
    var current: AppStringPack by mutableStateOf(ZhCnStrings)
}

/** 当前激活语言包的便捷只读入口。 */
val S: AppStringPack
    get() = AppStrings.current

/** 命名占位符替换工具，如 `"共 {count} 词".withArgs("count" to n)`，避免不同语序翻译时发生格式化异常。 */
fun String.withArgs(vararg args: Pair<String, Any?>): String {
    var result = this
    for ((key, value) in args) {
        result = result.replace("{$key}", value?.toString().orEmpty())
    }
    return result
}

